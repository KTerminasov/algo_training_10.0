"""
Ограничение времени: 1 с
Ограничение памяти: 64.0 Мб
Ввод: стандартный ввод или input.txt
Вывод: стандартный вывод или output.txt

В некотором царстве, в некотором государстве было N городов, и все они,
судя по главной карте императора, имели целые координаты. В те годы леса
были дремучие, дороги же строить умели только параллельно осям координат,
так что расстояние между двумя городами определялось как |x1 - x2| + |y1 - y2|.

Император решил построить N+1-ый город и сделать его столицей своего
государства, при этом координаты столицы также должны быть целыми. Место
для столицы следует выбрать так, чтобы среднее арифметическое расстояний
между столицей и остальными городами было как можно меньше. Однако,
разумеется, столицу нельзя строить на месте существующего города.

Нелегкая задача выбрать место для столицы поручена Вам.

Формат ввода:
В первой строке вводится число N - количество городов (1 <= N <= 100).
Следующие N строк содержат координаты городов - пары целых чисел,
не превышающих 1000 по абсолютной величине.

Формат вывода:
Выведите два целых числа - координаты точки, где следует построить столицу.
Если решений несколько, выведите любое.

Пример 1
Ввод:
8
0 0
1 0
2 0
0 1
2 1
0 2
1 2
2 2
Вывод:
1 1

Пример 2
Ввод:
4
0 0
1 1
0 1
1 0
Вывод:
0 -1
"""

def partition(a, x, left, r):
    "Разбивает a[left:r] относительно x. Возвращает (e, g):"
    "a[left:e] < x, a[e:g] == x, a[g:r] > x."""

    e = g = n = left
    while n < r:
        if a[n] > x:
            n += 1
        elif a[n] == x:
            a[g], a[n] = a[n], a[g]
            g += 1
            n += 1
        else:
            a[n], a[g], a[e] = a[g], a[e], a[n]
            e += 1
            g += 1
            n += 1
    
    return e, g


def kth(a, k):
    """к-ая порядковая статистика (с 0)."""
    a = a[:]  # Копируем исх. массив 
    lo, hi = 0, len(a)

    while True:
        x = a[(lo + hi) // 2]
        e, g = partition(a, x, lo, hi)

        if k < e:
            hi = e  # ищем слева
        elif k < g:
            return x  # попали в блок равных
        else:
            lo = g  # ищем справа


n = int(input())
xs, ys = [], []
cities = set()

for _ in range(n):
    x, y = map(int, input().split())
    xs.append(x)
    ys.append(y)
    cities.add((x, y))


xlo, xhi = kth(xs, (n - 1) // 2), kth(xs, n // 2)
ylo, yhi = kth(ys, (n - 1) // 2), kth(ys, n // 2)


# стоимости по каждой координате в окне поиска
F = {x: sum(abs(x - v) for v in xs) for x in range(xlo - n, xhi + n + 1)}
G = {y: sum(abs(y - v) for v in ys) for y in range(ylo - n, yhi + n + 1)}

best = None
for x in F:
    for y in G:
        if (x, y) in cities:
            continue
        c = F[x] + G[y]
        if best is None or c < best[0]:
            best = (c, x, y)

print(best[1], best[2])
