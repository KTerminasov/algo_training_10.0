"""
D. Пираты Баренцева моря

Ограничение времени: 1 с
Ограничение памяти: 64.0 Мб
Ввод: стандартный ввод или input.txt
Вывод: стандартный вывод или output.txt

Вася играет в настольную игру «Пираты Баренцева моря», которая посвящена
морским битвам. Игровое поле представляет собой квадрат из N x N клеток,
на котором расположено N кораблей (каждый корабль занимает одну клетку).

Вася решил воспользоваться линейной тактикой, для этого ему необходимо
выстроить все N кораблей в одном столбце. За один ход можно передвинуть
один корабль в одну из четырёх соседних по стороне клеток. Номер столбца,
в котором будут выстроены корабли, не важен. Определите минимальное
количество ходов, необходимых для построения кораблей в одном столбце.
В начале и процессе игры никакие два корабля не могут находиться в одной
клетке.

Формат ввода:
В первой строке входных данных задаётся число N (1 <= N <= 100).
В каждой из следующих N строк задаются координаты корабля: сначала номер
строки, затем номер столбца (нумерация начинается с единицы).

Формат вывода:
Выведите одно число — минимальное количество ходов, необходимое для
построения.

Пример
Ввод:
3
1 2
3 3
1 1
Вывод:
3

Примечание:
В примере необходимо выстроить корабли в столбце номер 2. Для этого
необходимо переставить корабль из клетки 3 3 в клетку 3 2 за один ход,
а корабль из клетки 1 1 в клетку 2 2 за два хода. Существуют и другие
варианты перестановки кораблей, однако ни в одном из них нет меньше
трёх ходов.
"""

def partition(a, x, left, r):
    """Разбивает a[left:r] относительно x. Возвращает (e, g):
    a[left:e] < x, a[e:g] == x, a[g:r] > x."""
    e = g = n = left
    while n < r:
        if a[n] > x:
            n += 1
        elif a[n] == x:
            a[g], a[n] = a[n], a[g]
            g += 1
            n += 1
        else:
            a[n], a[g], a[e] = a[g], a[e], a[n]
            e += 1
            g += 1
            n += 1
    return e, g


def kth(a, k):
    """k-я порядковая статистика (с 0)."""
    a = a[:]
    lo, hi = 0, len(a)
    while True:
        x = a[(lo + hi) // 2]
        e, g = partition(a, x, lo, hi)
        if k < e:
            hi = e
        elif k < g:
            return x
        else:
            lo = g


n = int(input())
rows, cols = [], []

for _ in range(n):
    r, c = map(int, input().split())
    rows.append(r)
    cols.append(c)

# 1) Горизонтальные ходы - все столбцы идут в медиану
median_col = kth(cols, n // 2)

moves = sum(abs(c - median_col) for c in cols)

# 2) Вертикальные ходы: i-й по порядку корабль идет в строку i (1..N)
rows.sort()
moves += sum(abs(r - (i + 1)) for i, r in enumerate(rows))

print(moves)
